# 3. Cargamos el modelo
filename = 'modelo-class.pkl'
try:
    modelo, labelencoder, variables, min_max_scaler = pickle.load(open(filename, 'rb'))
except Exception as e:
    st.error(f"No se pudo cargar el archivo del modelo: {e}")
    st.stop()

# 4. Interfaz Gráfica (Columnas para organizar los campos)
col1, col2 = st.columns(2)

with col1:
    age = st.number_input("Edad (age)", min_value=1, max_value=120, value=50)
    hypertension = st.selectbox("Hipertensión (hypertension)", ["No", "Yes"])
    heart_disease = st.selectbox("Enfermedad cardíaca (heart_disease)", ["No", "Yes"])

with col2:
    ever_married = st.selectbox("Casado/a (ever_married)", ["No", "Yes"])
    avg_glucose_level = st.number_input("Glucosa promedio (avg_glucose_level)", min_value=0.0, max_value=300.0, value=100.0)
    smoking_status = st.selectbox("Estado de fumador (smoking_status)", ["never smoked", "formerly smoked", "smokes", "Unknown"])

st.markdown("---")

# 5. Botón y procesamiento paso a paso organizado dentro del botón
if st.button("🔍 Predecir", type="primary"):

    # Creamos el DataFrame con los datos ingresados
    datos = [[age, hypertension, heart_disease, ever_married, avg_glucose_level, smoking_status]]
    data = pd.DataFrame(datos, columns=['age', 'hypertension', 'heart_disease', 'ever_married', 'avg_glucose_level', 'smoking_status'])

    # Preparación de Datos: Copia y Dummies
    data_preparada = data.copy()
    data_preparada = pd.get_dummies(data_preparada, columns=['hypertension', 'heart_disease', 'ever_married', 'smoking_status'], drop_first=False, dtype=int)

    # Se adicionan las columnas faltantes (reindex)
    data_preparada = data_preparada.reindex(columns=variables, fill_value=0)

    # Se normalizan únicamente las columnas numéricas
    columnas_num = ['age', 'avg_glucose_level']
    data_preparada[columnas_num] = min_max_scaler.transform(data_preparada[columnas_num])

    # Aplicamos el modelo para la predicción
    Y_pred = modelo.predict(data_preparada)

    # Decodificamos las predicciones a sus etiquetas originales
    resultado_original = labelencoder.inverse_transform(Y_pred)[0]

    # Mostramos los resultados en la interfaz con colores
    st.subheader("📊 Resultado del Análisis")

    if str(resultado_original).lower() in ["yes", "1", "true"]:
        st.error(f"⚠️ Alerta: El modelo predice un riesgo elevado (**{resultado_original}**).")
    else:
        st.success(f"✅ Resultado Favorable: Riesgo bajo (**{resultado_original}**).")

